#!/usr/bin/env bash
# Writes the production .env next to docker-compose.prod.yml, with fresh
# random secrets. Run it ON THE SERVER, once, from the project folder:
#
#   bash scripts/setup-production-env.sh
#
# It asks for your domain and admin email, generates every password and
# secret itself, and shows the admin password once. Secrets are created on
# the server and never leave it. It will not overwrite an existing .env.
set -euo pipefail

cd "$(dirname "$0")/.."
ENV_FILE=".env"

if [ -e "$ENV_FILE" ]; then
  echo "✗ $ENV_FILE already exists — not touching it. Move it away first if you really mean to start over."
  exit 1
fi
command -v openssl >/dev/null || { echo "✗ openssl is required"; exit 1; }

read -rp "Site domain (e.g. pupbox.ge): " DOMAIN
read -rp "Admin email [admin@${DOMAIN}]: " ADMIN_EMAIL
ADMIN_EMAIL="${ADMIN_EMAIL:-admin@${DOMAIN}}"

secret() { openssl rand -hex "$1"; }   # hex: safe inside URLs and quotes
POSTGRES_PASSWORD="$(secret 24)"
REDIS_PASSWORD="$(secret 24)"
ADMIN_PASSWORD="$(secret 12)"

umask 077   # the file is readable by its owner only
cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup-production-env.sh on $(date -u +%Y-%m-%d).
# Keep this file on the server only. Never commit it.

NODE_ENV="production"

# Database and cache (docker-compose.prod.yml builds the URLs from these)
POSTGRES_USER="pupbox"
POSTGRES_DB="pupbox_db"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD}"
REDIS_PASSWORD="${REDIS_PASSWORD}"

# Sign-in tokens
JWT_SECRET="$(secret 48)"
JWT_EXPIRES_IN="7d"
JWT_REFRESH_SECRET="$(secret 48)"
JWT_REFRESH_EXPIRES_IN="30d"

# First super admin, created by the seed. Change the password after first sign-in.
ADMIN_EMAIL="${ADMIN_EMAIL}"
ADMIN_PASSWORD="${ADMIN_PASSWORD}"

# Addresses
API_PORT=4000
API_PREFIX="api/v1"
WEB_PORT=3000
ADMIN_PORT=3001
NEXT_PUBLIC_SITE_URL="https://${DOMAIN}"
NEXT_PUBLIC_ADMIN_URL="https://admin.${DOMAIN}"
NEXT_PUBLIC_API_URL="https://api.${DOMAIN}/api/v1"
# Public address of the API itself, used in links to uploaded images
API_BASE_URL="https://api.${DOMAIN}"
# One front server (Caddy) passes on each visitor's real address, so rate
# limits apply per person. Port 4000 must then only be reachable through it.
TRUST_PROXY=1

# Email (Resend) — paste the key from resend.com when you have it
RESEND_API_KEY=""
EMAIL_FROM="noreply@${DOMAIN}"

# Payments (Flitt) — paste from the Flitt merchant portal when you have them
FLITT_MERCHANT_ID=""
FLITT_SECRET_KEY=""
FLITT_API_URL="https://pay.flitt.com"
FLITT_WEBHOOK_SECRET=""

# File storage (S3 compatible) — optional until product images are uploaded
S3_ENDPOINT=""
S3_REGION="us-east-1"
S3_ACCESS_KEY=""
S3_SECRET_KEY=""
S3_BUCKET="pupbox-media"
S3_PUBLIC_URL="https://media.${DOMAIN}"
EOF

echo
echo "✓ wrote $ENV_FILE (readable by you only)"
echo
echo "  Admin sign-in — save this in your password manager now, it is not shown again:"
echo "    email:    ${ADMIN_EMAIL}"
echo "    password: ${ADMIN_PASSWORD}"
echo
echo "  Still empty, fill in later: RESEND_API_KEY, FLITT_* keys, S3_* (optional)."
